#!/usr/bin/env python3
"""Seed demo trip: phone-side BLE payloads for the BWR tag (clock_nav.h).

Emits host_test/seed_demo.json (human-readable + hex, paste into
nRF Connect / web BLE console as writes to ...0002) and
firmware/bwr_hello/src/demo_steps.h (same payloads as C arrays, baked
into the device demo loop in main.c via demo.h/demo.c).

Payload shapes (firmware/bwr_hello/src/clock_nav.h):
  T + u8 h + u8 m | W + i8 temp + u8 icon | N + dist0 + instr0 | C
ASCII only, diacritics stripped phone-side (cf. esp32 keynote 5.6).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT_JSON = os.path.join(ROOT, "host_test", "seed_demo.json")
OUT_H = os.path.join(ROOT, "firmware", "bwr_hello", "src", "demo_steps.h")

ICON = {"sun": 0, "cloud": 1, "rain": 2, "snow": 3, "fog": 4}


def T(h, m):
    return bytes([ord("T"), h, m])


def W(temp, icon):
    return bytes([ord("W"), temp & 0xFF, ICON[icon]])


def N(dist, instr):
    b = b"N" + dist.encode() + b"\x00" + instr.encode() + b"\x00"
    assert len(b) <= 121, (dist, len(b))
    assert len(dist) < 24 and len(instr) < 64, (dist, instr)
    return b


def C():
    return b"C"


STEPS = [
    ("idle_ready", "morning, no nav", [T(8, 15), W(28, "sun"), C()], 0),
    ("highway", "long instr tests 2-line wrap", [N("84 km", "Di thang ve huong cao toc HN-HP")], 1),
    ("approach", "ve-huong split case", [N("500 m", "Re phai ve huong Vo Thi Sau")], 1),
    ("turn_now", "red dist + short instr", [T(8, 42), N("150 m", "Re phai vao Vo Thi Sau")], 1),
    ("arrive", "zero dist", [N("0 m", "Den noi: 123 Vo Thi Sau")], 1),
    ("done", "clear + clock update", [C(), T(9, 40)], 0),
]

doc = []
for name, desc, payloads, red in STEPS:
    doc.append({
        "name": name, "desc": desc, "expect_red": bool(red),
        "writes": [p.hex() for p in payloads],
    })
with open(OUT_JSON, "w") as f:
    json.dump(doc, f, indent=2)

with open(OUT_H, "w") as f:
    f.write("// Generated by tools/mkdemo.py — do not hand-edit.\n")
    f.write("#pragma once\n#include <stdint.h>\n#include <stddef.h>\n")
    for i, (name, desc, payloads, red) in enumerate(STEPS):
        f.write(f"// {i} {name}: {desc} expect_red={red}\n")
        for j, p in enumerate(payloads):
            f.write(f"static const uint8_t d{i}_{j}[] = {{{','.join(str(b) for b in p)}}};\n")
        f.write(f"static const uint8_t *d{i}_p[] = {{{','.join(f'd{i}_{j}' for j in range(len(payloads)))}}};\n")
        f.write(f"static const size_t d{i}_n[] = {{{','.join(str(len(p)) for p in payloads)}}};\n")
    f.write("static const uint8_t **demo_p[] = {"
            + ",".join(f"d{i}_p" for i in range(len(STEPS))) + "};\n")
    f.write("static const size_t *demo_n[] = {"
            + ",".join(f"d{i}_n" for i in range(len(STEPS))) + "};\n")
    f.write("static const int demo_k[] = {"
            + ",".join(str(len(p)) for _, _, p, _ in STEPS) + "};\n")
    f.write("static const char *demo_name[] = {"
            + ",".join(f'"{n}"' for n, _, _, _ in STEPS) + "};\n")
    f.write("static const int demo_red[] = {"
            + ",".join(str(r) for _, _, _, r in STEPS) + "};\n")
    f.write(f"#define DEMO_STEPS {len(STEPS)}\n")
print(f"OK steps={len(STEPS)} json=host_test/seed_demo.json steps=firmware/bwr_hello/src/demo_steps.h")
for s in doc:
    print(f"- {s['name']}: {' '.join(s['writes'])}")
