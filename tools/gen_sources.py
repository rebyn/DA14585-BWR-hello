#!/usr/bin/env python3
"""Emit build/sources.mk from ancestor/Keil_5/ble_app_peripheral.uvprojx.

Maps Keil-relative paths onto --sdk/--ancestor trees, honors per-file
IncludeInBuild, and swaps the ARMASM startup for the SDK GCC pair
(ivtable + startup). Same mapping as tools/ci_compile.py.
"""
import argparse, os, xml.etree.ElementTree as ET

def conv(p, anc, keil, sdk):
    p = p.strip().replace('\\', '/')
    if p.startswith('./../../../../../'): return sdk + '/' + p[len('./../../../../../'):]
    if p.startswith('../../../../../'): return sdk + '/' + p[len('../../../../../'):]
    if p.startswith('../'): return anc + '/' + p[len('../'):]
    if p.startswith('./'): return keil + '/' + p[len('./'):]
    return keil + '/' + p

ARM_STARTUP = 'startup_DA14585_586.s'   # ARMASM syntax: unassemblable by GCC
GCC_STARTUP = [
    'sdk/platform/arch/boot/GCC/ivtable_DA14585_586.S',
    'sdk/platform/arch/boot/GCC/startup_DA14585_586.S',
]

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sdk', required=True)
    ap.add_argument('--ancestor', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    sdk = a.sdk
    if os.path.basename(sdk.rstrip('/')) != '6.0.22.1401':
        cand = os.path.join(sdk, 'DA145xx_SDK', '6.0.22.1401')
        sdk = cand if os.path.isdir(cand) else sdk
    anc, keil = a.ancestor, os.path.join(a.ancestor, 'Keil_5')
    t = ET.parse(os.path.join(keil, 'ble_app_peripheral.uvprojx'))
    incs, cfiles, skipped = [], [], 0
    for e in t.getroot().iter('IncludePath'):
        if e.text:
            for p in e.text.split(';'):
                q = conv(p, anc, keil, sdk)
                if q not in incs: incs.append(q)
    for f in t.getroot().iter('File'):
        n, p = f.findtext('FileName'), f.findtext('FilePath')
        if not (n and p): continue
        if f.findtext('FileOption/CommonProperty/IncludeInBuild') == '0':
            skipped += 1
            continue
        if n.endswith('.c'):
            cfiles.append(conv(p, anc, keil, sdk))
        elif n == ARM_STARTUP:
            skipped += 1   # replaced below by the GCC pair
    with open(a.out, 'w') as o:
        o.write('# generated by tools/gen_sources.py - do not edit\n')
        o.write('C_SRCS := \\\n')
        for q in cfiles:
            o.write(f'  {q} \\\n')
        o.write('\nS_SRCS := \\\n')
        for rel in GCC_STARTUP:
            o.write(f'  {sdk}/{rel} \\\n')
        o.write('  $(THISDIR)/region_table.S\n')
        o.write('\nINCLUDES := \\\n')
        for q in incs:
            o.write(f'  -I{q} \\\n')
        o.write('\nFORCE_INC := -include da14585_config_basic.h '
                '-include da14585_config_advanced.h -include user_config.h\n')
    print(f"sources.mk: {len(cfiles)} C + {len(GCC_STARTUP)+1} asm, "
          f"{len(incs)} includes, {skipped} skipped")

if __name__ == '__main__':
    main()
